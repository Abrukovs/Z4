/**
 * Правила редакции «Ставки дня».
 *
 * 1) Минимальный коэффициент (запрос 29.09): «в Ставку дня не должны попадать
 *    события с коэффициентом до 1,5 средним». Победа явного фаворита за
 *    1.05–1.35 не окупает риск → порог 1.50. Проверяются ДВЕ линии:
 *     - наш опубликованный кэф — не ниже 1.50;
 *     - если линия рынка уже известна (web-search, Bet.marketOdds) — и
 *       рыночный кэф не ниже 1.50.
 *
 * 2) Известные турниры (запросы 03.10): «в Ставке дня Вторая лига РФ, у меня
 *    в конторе такой нету». Низшие лиги предлагать МОЖНО — но только в ленте
 *    прогнозов, НЕ в Ставку дня. Для футбола действует БЕЛЫЙ СПИСОК:
 *     - топ-лиги (АПЛ, Ла Лига, Серия А, Бундеслига, Лига 1, РПЛ…);
 *     - соревнования сборных (Лига наций, ЧМ/ЕВРО, отборы, Кубок Америки…);
 *     - известные вторые дивизионы и чемпионаты из списка пользователя
 *       (Первая лига РФ, Чемпионшип/Лига 1/Лига 2 Англии, Сегунда,
 *       Бундеслига-2, Серия B, Лига 2 Франция, Элитсерия, Вейккауслиига,
 *       Лига 1 Румынии, Бразилия, Аргентина и т.д.).
 *    Теннис — только топ-уровень (основной тур ATP/WTA, Шлемы, Мастерс,
 *    командные кубки): челленджеры остаются в ленте и у «звезды» (Task 37),
 *    но не в главной ставке сайта.
 *    Фолбэк: если в окне подбора нет НИ ОДНОГО подходящего прогноза —
 *    остаётся лучший из имеющихся (пустой hero хуже).
 */

/** Минимальный коэффициент «Ставки дня» */
export const MIN_BOD_ODDS = 1.5

/* ------------------------- Топ-уровень тенниса ------------------------- */

/** Низший теннис: челленджеры, ITF, квалификации, парные блоки, выставки */
export const TENNIS_LOW_RE = /челлендж|challenger|\bitf\b|квалифик|пары|выставоч|показат/i

/** Крупнейшие турниры: Большой шлем, Итоги, командные кубки, Мастерс */
const TENNIS_MAJOR_RE =
  /большой шлем|us open|уимблдон|ролан гаррос|австрали|мастерс|финал[ыи]? (atp|wta)|united cup|кубок дэвиса|billie jean|hopman/i

/** Основной тур (как его подписывает источник): «ATP. …», «WTA. …», «АТР. …» */
const TENNIS_MAIN_TOUR_RE = /^(atp|wta|атр)\b/i

/**
 * Топ-уровень тенниса: турниры, которые есть в линии ЛЮБОЙ конторы —
 * Большой шлем, итоговые турниры, Мастерс, основной тур ATP/WTA,
 * командные кубки. Челленджеры, ITF, квалификации, парные блоки и
 * выставки — НЕ топ-уровень (для «Ставки дня»), но в ленте прогнозов
 * и в прогнозах «звезды» остаются (Task 37: «оставляем Марию такой»).
 */
export function isTopTennisEvent(league: string): boolean {
  const l = league.toLowerCase()
  if (TENNIS_LOW_RE.test(l)) return false
  if (TENNIS_MAJOR_RE.test(l)) return true
  return TENNIS_MAIN_TOUR_RE.test(l)
}

/** Понижение низшего тенниса в приоритете отбора ленты (не запрет) */
export const TENNIS_LOW_PENALTY = 12

/* -------------------- Белый список лиг (футбол, BOD) -------------------- */

/** Женский футбол — в «Ставку дня» не берём (проверяется до всего) */
const FOOTBALL_WOMEN_RE = /женск|женщин|\(ж\)/i

/**
 * Турниры сборных: Лига наций, ЧМ/ЕВРО, отборочные, Кубок Америки/Азии/
 * Африки, товарищеские СБОРНЫХ. Молодёжные ЧЕ/ЧМ (U21) — тоже сборные и
 * есть в линиях контор (проверяются ДО клубных отклонений).
 */
const FOOTBALL_NT_RES: RegExp[] = [
  /лига наций/,
  /чемпионат мира/,
  /чемпионат европы/,
  /отбор/,
  /кубок америк/,
  /кубок азии/,
  /кубок африк/,
  /товарищеские\s+матчи\s*[.·]?\s*сборн/,
  /финалиссим/,
]

/** Международные клубные турниры */
const FOOTBALL_INTL_CLUB_RES: RegExp[] = [
  /лига чемпионов/,
  /лига европы/,
  /лига конференций/,
  /суперкубок уефа/,
  /клубн\w*\s+чемпионат мира/,
]

/**
 * Клубные отклонения (после сборных): юниорские/молодёжные/резервные
 * команды клубов — «Чемпионат Англии. Премьер-лига 2 (до 21)» и т.п.
 */
const FOOTBALL_YOUTH_RES: RegExp[] = [
  /юниор/,
  /молод[её]жн/,
  /молодежн/,
  /двойн/,
  /до\s*(19|21|23)\s*(года|лет|$)/,
  /премьер[\s-]*лиг[ау]?\s*2\b/,
]

/**
 * Страна + турнир: лига проходит в белый список, если название содержит
 * И страну, И разрешённый турнир из её списка. Вт. дивизионы разрешённых
 * стран — только те, что назвал пользователь (Чемпионшип, Сегунда,
 * Серия B, Лига 2, Бундеслига-2, Элитсерия, финская, румынская…).
 * Анкер ^…$ — защита от «Чемпионат Украины. Первая лига» (не топ).
 */
interface CountryLeagueRule {
  country: RegExp
  comp: RegExp
}

const FOOTBALL_COUNTRY_RULES: CountryLeagueRule[] = [
  // Россия: РПЛ, Первая лига, кубки (Вторая лига и ниже — вне списка)
  { country: /росси|\bрф\b|\bрпл\b/i, comp: /премьер|первая\s+лиг|\bрпл\b|кубок|суперкубок/i },
  // Англия: АПЛ, Чемпионшип, Лига 1/2, кубки
  { country: /англ/i, comp: /премьер|чемпионшип|премьершип|лиг[ау]\s*[12]\b|кубок|суперкубок|efl/i },
  // Испания: Ла Лига, Сегунда, кубки
  { country: /испан/i, comp: /ла\s+лиг|примьер|пример|сегунд|кубок|суперкубок/i },
  // Германия: Бундеслига и Бундеслига-2, кубки
  { country: /герман/i, comp: /бундеслиг|кубок|суперкубок/i },
  // Италия: Серия А, Серия B, кубки
  { country: /итал/i, comp: /сери[яюи]\s*[аabб]|кубок|суперкубок/i },
  // Франция: Лига 1, Лига 2, кубки
  { country: /франц/i, comp: /лиг[ау]\s*[12]\b|кубок|суперкубок/i },
  // Португалия, Нидерланды, Турция, Бельгия, Украина
  { country: /португал/i, comp: /премьер|примьер|пример|кубок|суперкубок/i },
  { country: /нидерланд|голланд/i, comp: /эредивиз|кубок/i },
  { country: /турц/i, comp: /суперлиг|кубок/i },
  { country: /бельг/i, comp: /про[-\s]?лиг|кубок/i },
  { country: /украин/i, comp: /премьер|^чемпионат\s+украины$/i },
  // Скандинавия и Финляндия (по списку пользователя)
  { country: /норвег/i, comp: /элитсери/i },
  { country: /швец/i, comp: /алльсвенскан/i },
  { country: /дани/i, comp: /суперлиг/i },
  { country: /финлянд/i, comp: /вейккаусли|veikkausliig|^чемпионат\s+финляндии$/i },
  // Восточная и Центральная Европа
  { country: /польш/i, comp: /экстраклас/i },
  { country: /чех/i, comp: /фортун|гамбринус/i },
  { country: /австр/i, comp: /бундеслиг/i },
  { country: /швейцар/i, comp: /суперлиг/i },
  { country: /грец/i, comp: /суперлиг/i },
  { country: /хорват/i, comp: /первая\s+лиг|hnl/i },
  { country: /румын/i, comp: /лиг[ау]\s*1\b|лига\s*i\b/i },
  { country: /казахстан/i, comp: /премьер/i },
  // Америки и Азия
  { country: /бразил/i, comp: /сери[яю]\s*[аa]$|^чемпионат\s+бразилии$/i },
  { country: /аргентин/i, comp: /примьер|пример|профессион|^чемпионат\s+аргентины$/i },
  { country: /сша|америк/i, comp: /^чемпионат\s+сша$|mls|\bмлс\b/i },
  { country: /мексик/i, comp: /пример|лиг[ау]?\s*mx|^чемпионат\s+мексики$/i },
  { country: /саудов/i, comp: /премьер|про[-\s]?лиг/i },
]

/**
 * Известная лига для «Ставки дня» (футбол)? Белый список: турниры сборных,
 * международные клубные, топ-чемпионаты и разрешённые вторые дивизионы.
 * «Чемпионат России. Вторая Лига. Группа Б» — НЕ проходит (вторая лига РФ
 * вне списка: остаётся в ленте прогнозов, но не в главной ставке).
 */
export function isKnownFootballLeague(league: string | null | undefined): boolean {
  if (!league) return false
  const s = league.toLowerCase()
  if (FOOTBALL_WOMEN_RE.test(s)) return false
  if (FOOTBALL_NT_RES.some((re) => re.test(s))) return true
  if (FOOTBALL_INTL_CLUB_RES.some((re) => re.test(s))) return true
  if (FOOTBALL_YOUTH_RES.some((re) => re.test(s))) return false
  return FOOTBALL_COUNTRY_RULES.some((r) => r.country.test(s) && r.comp.test(s))
}

/**
 * Годится ли прогноз в «Ставку дня»:
 *  - наш кэф ≥ 1.50 и (когда известна) линия рынка ≥ 1.50;
 *  - футбол — лига из белого списка (топ-лиги, сборные, известные
 *    вторые дивизионы по списку пользователя);
 *  - теннис — топ-уровень (основной тур/Шлемы/Мастерс, без челленджеров);
 *  - хоккей/баскетбол — только правило кэфа (КХЛ/НХЛ/ВХЛ, Евролига, ВТБ —
 *    есть в линиях; отдельных ограничений пользователь не просил).
 */
export function isBodEligible(bet: {
  odds: number
  marketOdds?: number | null
  league?: string | null
  sport?: string | null
}): boolean {
  if (bet.odds < MIN_BOD_ODDS) return false
  if (bet.marketOdds != null && bet.marketOdds < MIN_BOD_ODDS) return false
  if (bet.sport === 'football') return isKnownFootballLeague(bet.league)
  if (bet.sport === 'tennis') return isTopTennisEvent(bet.league ?? '')
  return true
}
